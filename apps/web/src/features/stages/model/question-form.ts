import { z } from "zod";
import type { Question, QuestionType } from "./schemas";

/** Option rows the form always shows; the first two are needed, the rest optional. */
export const QUESTION_OPTION_ROWS = 6;
export const QUESTION_MIN_OPTIONS = 2;
export const OPTION_BODY_MAX = 500;
export const QUESTION_POINTS_MAX = 100;

export const QUESTION_BODY_REQUIRED = "Nhập nội dung câu hỏi.";
export const QUESTION_POINTS_RANGE = "Điểm của câu hỏi là số nguyên từ 1 đến 100.";
export const QUESTION_TOO_FEW_OPTIONS = "Câu hỏi cần ít nhất 2 phương án.";
export const OPTION_BODY_TOO_LONG = "Nội dung phương án từ 1 đến 500 ký tự.";
export const QUESTION_NEEDS_CORRECT = "Đánh dấu ít nhất một đáp án đúng.";
export const SINGLE_HAS_ONE_CORRECT = 'Câu một đáp án chỉ có một phương án đúng. Đổi sang "Nhiều đáp án" nếu cần.';

export const QUESTION_TYPE_LABEL: Record<QuestionType, string> = { single: "Một đáp án", multi: "Nhiều đáp án" };

const optionRowSchema = z.object({
  /** Empty for a new option; an existing option keeps its id so learners' answers stay attached. */
  id: z.string(),
  body: z.string(),
  correct: z.boolean(),
});

/**
 * "Thêm câu hỏi"/"Sửa câu hỏi" values. Blank option rows are left out, a ticked "Đúng" on one
 * included; the rules and messages are the server's, checked on the options that would be sent.
 */
export const questionFormSchema = z
  .object({
    bodySource: z.string().trim().min(1, QUESTION_BODY_REQUIRED),
    type: z.enum(["single", "multi"]),
    points: z
      .string()
      .trim()
      .refine((s) => /^\d+$/.test(s) && Number(s) >= 1 && Number(s) <= QUESTION_POINTS_MAX, QUESTION_POINTS_RANGE)
      .transform(Number),
    options: z.array(optionRowSchema).length(QUESTION_OPTION_ROWS),
    explanationSource: z.string().trim(),
  })
  .superRefine((values, ctx) => {
    values.options.forEach((option, index) => {
      if (Array.from(option.body.trim()).length > OPTION_BODY_MAX) {
        ctx.addIssue({ code: "custom", path: ["options", index, "body"], message: OPTION_BODY_TOO_LONG });
      }
    });
    const filled = values.options.filter((o) => o.body.trim() !== "");
    const correct = filled.filter((o) => o.correct).length;
    let message: string | undefined;
    if (filled.length < QUESTION_MIN_OPTIONS) message = QUESTION_TOO_FEW_OPTIONS;
    else if (correct === 0) message = QUESTION_NEEDS_CORRECT;
    else if (values.type === "single" && correct > 1) message = SINGLE_HAS_ONE_CORRECT;
    if (message) ctx.addIssue({ code: "custom", path: ["options", "root"], message });
  });
export type QuestionFormValues = z.input<typeof questionFormSchema>;
export type QuestionFormOutput = z.output<typeof questionFormSchema>;

/** Body of `POST …/questions` and `PATCH …/questions/{qid}` (a full replace); the key is generated by the server. */
export interface QuestionBody {
  type: QuestionType;
  bodySource: string;
  explanationSource: string;
  points: number;
  options: { id?: string; body: string; correct: boolean }[];
}

export function toQuestionBody(values: QuestionFormOutput): QuestionBody {
  return {
    type: values.type,
    bodySource: values.bodySource,
    explanationSource: values.explanationSource,
    points: values.points,
    options: values.options
      .filter((o) => o.body.trim() !== "")
      .map((o) => ({ ...(o.id ? { id: o.id } : {}), body: o.body.trim(), correct: o.correct })),
  };
}

/** The question being edited padded to six rows, else a blank one-point single-answer question. */
export function questionFormDefaults(question?: Question): QuestionFormValues {
  const rows = Array.from({ length: QUESTION_OPTION_ROWS }, (_, i) => {
    const option = question?.options[i];
    return { id: option?.id ?? "", body: option?.body ?? "", correct: option?.isCorrect ?? false };
  });
  return {
    bodySource: question?.bodySource ?? "",
    type: question?.type ?? "single",
    points: String(question?.points ?? 1),
    options: rows,
    explanationSource: question?.explanationSource ?? "",
  };
}

/** Whether a saved question has no option marked correct (it blocks publishing). */
export function lacksCorrectAnswer(question: Pick<Question, "options">): boolean {
  return !question.options.some((o) => o.isCorrect);
}

/** Sum of the question points. */
export function quizTotalPoints(questions: readonly Pick<Question, "points">[]): number {
  return questions.reduce((sum, q) => sum + q.points, 0);
}

/** "{n} câu · {total} điểm" under the question list's heading. */
export function questionCountLabel(questions: readonly Pick<Question, "points">[]): string {
  return `${String(questions.length)} câu · ${String(quizTotalPoints(questions))} điểm`;
}
